import { z } from 'zod';
import { daysBetween, today } from './chronos.js';
import { CURRENCIES, EVENT_TYPES, LANGUAGES, MAX_LEAD_DAYS, PRIORITIES } from './constants.js';

// Screen out control characters (excluding tab, line break, carriage return) and bidi overrides
const DISALLOWED_CONTROL_CHARS = /(?![\t\n\r])\p{Cc}|[\u202A-\u202E\u2066-\u2069]/u;

/**
 * Validates user-supplied text with character limits and control character checks.
 * @param {number} maxCharLimit
 */
const sanitizedText = (maxCharLimit) =>
  z
    .string()
    .trim()
    .max(maxCharLimit, `Use ${maxCharLimit} characters or fewer.`)
    .refine(
      (text) => !DISALLOWED_CONTROL_CHARS.test(text),
      'Remove unsupported control characters.',
    );

/**
 * Validates that an event date falls within the allowable advance scheduling window.
 * 1 day of backward tolerance is granted to account for time zones behind UTC.
 * @param {string} candidateDate ISO date string (YYYY-MM-DD)
 */
const isWithinPlanningHorizon = (candidateDate) => {
  const leadDays = daysBetween(today(), candidateDate);
  return leadDays >= -1 && leadDays <= MAX_LEAD_DAYS;
};

export { MAX_LEAD_DAYS } from './constants.js';
export const EventSchema = z.strictObject({
  type: z.enum(EVENT_TYPES),
  name: sanitizedText(80).default(''),
  date: z.iso
    .date('Enter a valid date.')
    .refine(isWithinPlanningHorizon, 'Choose a date between today and three years from now.'),
  guests: z
    .int('Enter a whole number of guests.')
    .min(1, 'At least one guest is needed.')
    .max(10_000, 'Plans support up to 10,000 guests.'),
  budget: z
    .number('Enter your total budget as a number.')
    .min(1, 'Enter a budget of at least 1.')
    .max(10_000_000_000, 'Enter a smaller budget.'),
  currency: z.enum(CURRENCIES),
  location: sanitizedText(100).min(2, 'Enter a city, area or venue.'),
  preferences: sanitizedText(600).default(''),
  language: z.enum(Object.keys(LANGUAGES)).default('en'),
});

/**
 * Validates string content produced by GenAI or client refinement feedback.
 * @param {number} maxCharLimit
 * @param {string} promptDescription Guidance forwarded to the model schema
 */
const modelText = (maxCharLimit, promptDescription) =>
  z
    .string()
    .trim()
    .min(1)
    .max(maxCharLimit)
    .refine((text) => !DISALLOWED_CONTROL_CHARS.test(text))
    .describe(promptDescription);

/** Schema representing the structured response generated by Gemini */
export const PlanSchema = z.object({
  title: modelText(100, 'Short, celebratory title for this plan'),
  summary: modelText(
    700,
    'Two or three sentences on the concept and how to use the budget and time',
  ),
  budget: z
    .array(
      z.object({
        category: modelText(60, 'Spending category, e.g. Venue or Catering'),
        percent: z
          .number()
          .describe(
            'Share of the total budget in percent. Items sum to 100 unless the user asks ' +
              'to spend less; the rest is kept as savings',
          ),
        note: modelText(240, 'What this covers plus one money-saving tip'),
      }),
    )
    .min(3)
    .max(10),
  timeline: z
    .array(
      z.object({
        daysBefore: z.int().describe('Whole days before the event; 0 is the event day'),
        task: modelText(240, 'One concrete action to complete'),
      }),
    )
    .min(3)
    .max(14),
  vendors: z
    .array(
      z.object({
        type: modelText(60, 'Vendor or service to book, e.g. Photographer'),
        priority: z.enum(PRIORITIES),
        bookDaysBefore: z.int().describe('Book at least this many days before the event'),
        tip: modelText(240, 'What to ask or compare before booking'),
      }),
    )
    .min(2)
    .max(10),
  ideas: z
    .array(
      z.object({
        title: modelText(80, 'Catchy name for the idea'),
        description: modelText(400, 'How to bring it to life and why it suits this event'),
      }),
    )
    .min(2)
    .max(6),
});

/** Request payload contract for POST /api/plan */
export const PlanRequestSchema = z.strictObject({
  event: EventSchema,
  refine: z
    .strictObject({
      plan: PlanSchema,
      feedback: sanitizedText(400).min(3, 'Describe what you would like to change.'),
    })
    .optional(),
});

/**
 * Gemini-compliant JSON schema generated directly from PlanSchema.
 * Min/max bounds are stripped to avoid schema validation errors during decoding.
 */
export const PLAN_JSON_SCHEMA = z.toJSONSchema(PlanSchema, {
  override: ({ jsonSchema }) => {
    delete jsonSchema.minimum;
    delete jsonSchema.maximum;
  },
});
delete PLAN_JSON_SCHEMA.$schema;

